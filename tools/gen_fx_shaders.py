def inject(text, anchor, block, what):
    i = text.find(anchor)
    if i < 0:
        sys.exit(f"anchor not found ({what}): {anchor!r}")
    if text.find(anchor, i + 1) >= 0:
        sys.exit(f"anchor not unique ({what}): {anchor!r}")
    j = i + len(anchor)
    return text[:j] + block + text[j:]


def check(ver, name, text):
    if text.count("{") != text.count("}"):
        sys.exit(f"{ver} {name}: unbalanced braces")
    if text.count("#if") != text.count("#endif"):
        sys.exit(f"{ver} {name}: unbalanced preprocessor")


def gen(ver, src_dir, base):
    src = REPO / "tools" / "vanilla_shaders" / src_dir
    dst = REPO / f"ogfx_{ver}/assets/minecraft/shaders/core"
    dst.mkdir(parents=True, exist_ok=True)
    vsh = (src / f"{base}.vsh").read_text(encoding="utf-8")
    fsh = (src / f"{base}.fsh").read_text(encoding="utf-8")

    vsh = inject(vsh, "#moj_import <minecraft:projection.glsl>\n", VSH_DECL, f"{ver} vsh decl")
    vcolor = "        vertexColor = vec4(1.0);"
    if "out vec4 lightMapColor;" in vsh:
        vcolor += "\n        lightMapColor = vec4(1.0);"
    tail = VSH_MAIN_TAIL.replace("%%VERTEX_COLOR%%", vcolor)
    last = vsh.rstrip().rfind("}")
    vsh = vsh[:last] + tail + vsh[last:]
    for must in ("vertexColor", "Position", "Normal", "UV2", "ProjMat", "ModelViewMat", "in vec4 Color;"):
        if must not in vsh:
            sys.exit(f"{ver} vsh: expected symbol {must} missing")

    fsh = inject(fsh, "#moj_import <minecraft:dynamictransforms.glsl>\n", FSH_DECL, f"{ver} fsh decl")
    overlay = ("        ogC.rgb = mix(overlayColor.rgb, ogC.rgb, overlayColor.a);"
               if "in vec4 overlayColor;" in fsh else "")
    head = FSH_MAIN_HEAD.replace("%%OVERLAY%%", overlay)
    fsh = inject(fsh, "void main() {\n", head, f"{ver} fsh main")
    for must in ("apply_fog(", "uniform sampler2D Sampler0;", "in vec2 texCoord0;"):
        if must not in fsh:
            sys.exit(f"{ver} fsh: expected symbol {must} missing")

    check(ver, "vsh", vsh)
    check(ver, "fsh", fsh)
    (dst / f"{base}.vsh").write_text(vsh, encoding="utf-8", newline="\n")
    (dst / f"{base}.fsh").write_text(fsh, encoding="utf-8", newline="\n")
    print(f"ogfx_{ver}: ok ({base})")


if __name__ == "__main__":
    for v, (src_dir, base) in VERSIONS.items():
        gen(v, src_dir, base)
