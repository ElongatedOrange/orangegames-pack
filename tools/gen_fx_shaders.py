"""Inject OrangeGames FX into the vanilla ITEM core shaders.

Items (held, dropped, ItemDisplays, item frames) do NOT render through
core/entity - they use rendertype_item_entity_translucent_cull.{vsh,fsh} on
1.21.6-1.21.11 and item.{vsh,fsh} on 26.1+. The vanilla sources are vendored in
tools/vanilla_shaders/<ver>/ (extracted from the official client jars) and this
script writes ogfx_<ver>/assets/minecraft/shaders/core/<name>.{vsh,fsh}.
ModelEngine's entity shaders are left alone.

Only version families whose vanilla shader has been verified from a real jar
get an overlay (see VERSIONS); anything else renders the markers as a plain
near-white tint. A compile error disables the whole pack on that client, so
keep the GLSL conservative (#version follows the vanilla file).

Marker convention (shared with tools/gen_fx_art.py):
    vertex Color == (255, 254 - sub, 255 - FXID)/255   sub = 0..54, FXID = 1..15
    -> near-white when unshaded (Bedrock, unsupported Java versions)
    FX ids: 1 prism core, 2 prism slash, 3 (unused), 4 nova ring,
            5 tesla bolt, 6 tesla coil orb, 10 screen overlay (per-viewer
            fullscreen quad), 11 gpu sparks, 12 blade ghost, 13 holo edge,
            14 nova sphere (billboarded quad ray-cast as a sphere whose surface
            is a refracted parallax starfield - the end-portal look),
            15 tesla sphere (same, electric palette + crackle; param.y = zap surge)
Per-entity parameters ride in UV2 (ItemDisplay brightness): block light ->
ogParam.x, sky light -> ogParam.y, each 0..1 in 1/15 steps.
"""
